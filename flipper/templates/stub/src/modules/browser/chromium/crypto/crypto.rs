use anyhow::Result;
use chacha20::{
    ChaCha20,
    cipher::{KeyIvInit, StreamCipher},
};

// Decryption key and nonce (must match the C++ version)
const DECRYPTION_KEY: [u8; 32] = [
    0x1B, 0x27, 0x55, 0x64, 0x73, 0x8B, 0x9F, 0x4D, 0x58, 0x4A, 0x7D, 0x67, 0x8C, 0x79, 0x77, 0x46,
    0xBE, 0x6B, 0x4E, 0x0C, 0x54, 0x57, 0xCD, 0x95, 0x18, 0xDE, 0x7E, 0x21, 0x47, 0x66, 0x7C, 0x94,
];

const DECRYPTION_NONCE: [u8; 12] = [
    0x4A, 0x51, 0x78, 0x62, 0x8D, 0x2D, 0x4A, 0x54, 0x88, 0xE5, 0x3C, 0x50,
];

pub fn chacha20_decrypt(data: &mut [u8]) -> Result<()> {
    let mut cipher = ChaCha20::new(&DECRYPTION_KEY.into(), &DECRYPTION_NONCE.into());
    cipher.apply_keystream(data);
    Ok(())
}
